"""Index the workspace: write the shared drive's INDEX.md, and the tree in WORKSPACE.md.

Usage: py -3.12 tools/workspace/index.py [--check]

1. <shared>/INDEX.md lists every file on the shared drive, per top-level folder, with its size and the date it was
   last saved, so people and agents can see what exists without crawling the drive. Folder READMEs are left out:
   they are the structure, not the content.
2. WORKSPACE.md gets the workspace's tree (folders only) between <!-- TREE:BEGIN --> and <!-- TREE:END -->.

Office lock files (~$*), desktop.ini, .DS_Store, Thumbs.db and hidden files are skipped. --check changes nothing and
exits 1 when either output is stale. Output is sorted and has no clock in it: the same tree gives the same files.
"""
from __future__ import annotations

import argparse
import datetime as dt
import sys
from pathlib import Path
from urllib.parse import quote

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # tools/, so the workspace package imports
from workspace import config  # noqa: E402

SKIP_FILES = {"desktop.ini", ".DS_Store", "Thumbs.db", "INDEX.md", "README.md"}
SKIP_DIRS = {".git", ".claude", ".idea", ".vscode", ".venv", "__pycache__", "node_modules", ".pytest_cache",
             "graphify-out", ".gitnexus"}  # local tool output is not part of the map
SHOWN_HIDDEN = {".agents", ".github"}
GOV_NOTES = {
    ".agents": "skills, shared by every agent tool",
    ".github": "Copilot's entry file",
    "architecture": "ADRs, deviations, questions",
    "operations": "schedules, notifications, ports",
    "prd": "the PRD mirror and its sync",
    "resources": "UI kit, brainstorms, plans, debug, audits",
    "tests": "checks for the tools and agent files",
    "tools": "deterministic tools, one folder per job",
}


def visible(path: Path) -> bool:
    name = path.name
    if path.is_dir():
        return name not in SKIP_DIRS and (not name.startswith(".") or name in SHOWN_HIDDEN)
    return name not in SKIP_FILES and not name.startswith(("~$", "."))


def folders(path: Path) -> list[Path]:
    return sorted((p for p in path.iterdir() if p.is_dir() and visible(p)), key=lambda p: p.name.lower())


def size(n: int) -> str:
    if n < 1024:
        return f"{n} B"
    if n < 1024 * 1024:
        return f"{round(n / 1024)} KB"
    return f"{n / 1024 / 1024:.1f} MB"


def files_in(path: Path) -> list[Path]:
    found = []
    for item in sorted(path.iterdir(), key=lambda p: p.name.lower()):
        if not visible(item):
            continue
        found += files_in(item) if item.is_dir() else [item]
    return found


def index(shared: Path) -> str:
    sections, total = [], 0
    top_files = [p for p in sorted(shared.iterdir(), key=lambda p: p.name.lower()) if p.is_file() and visible(p)]
    groups = ([("(top level)", shared, top_files)] if top_files else []) + \
             [(folder.name, folder, files_in(folder)) for folder in folders(shared)]
    for name, folder, found in groups:
        total += len(found)
        sections += ["", f"## {name}", ""]
        if not found:
            sections.append("_No files yet: see the folder's README for what goes here._")
            continue
        sections += ["| File | Size | Saved |", "|---|---|---|"]
        for path in found:
            rel = path.relative_to(shared).as_posix()
            shown = path.relative_to(folder).as_posix()
            saved = dt.date.fromtimestamp(path.stat().st_mtime).isoformat()
            sections.append(f"| [{shown}]({quote(rel)}) | {size(path.stat().st_size)} | {saved} |")
    head = ["# Shared workspace index",
            "",
            "> Generated by `tools/workspace/index.py` in the governance repository (the `gov-workspace-map` skill). "
            "Do not edit: every run rewrites it. Folder READMEs say what belongs where.",
            f"> {total} files in {len(groups)} folders."]
    return "\n".join(head + sections) + "\n"


def tree(ws: config.Workspace) -> str:
    root, shared, git_dir = ws.workspace_dir, ws.shared, ws.git_dir
    lines = [f"{root.name}/"]

    def note(path: Path) -> str:
        if path == shared:
            return "the shared drive (synced; a link in a real workspace)"
        if path == ws.root:
            return "this repository"
        if path.parent == git_dir:
            return next((r.get("role", "") for r in ws.repos if r.get("slug") == path.name), "")
        if path.parent == ws.root:
            return GOV_NOTES.get(path.name, "")
        return ""

    # How many levels to show below a folder: the shared drive two, git/ and this repository one, others none.
    expand = {shared: 2, git_dir: 1, ws.root: 1}

    def walk(path: Path, levels: int, prefix: str) -> None:
        children = folders(path)
        for i, child in enumerate(children):
            last = i == len(children) - 1
            label = f"{prefix}{'└── ' if last else '├── '}{child.name}/"
            text = note(child)
            lines.append(f"{label:<44}{text}" if text else label)
            below = max(levels - 1, expand.get(child, 0))
            if below:
                walk(child, below, prefix + ("    " if last else "│   "))

    walk(root, 1, "")
    if shared.parent != root:
        lines += ["", f"shared drive: {shared}"]
    return "```\n" + "\n".join(lines) + "\n```"


def main() -> int:
    p = argparse.ArgumentParser(description="Write the shared drive's INDEX.md and the tree in WORKSPACE.md.")
    p.add_argument("--check", action="store_true", help="exit 1 if either output is stale; change nothing")
    args = p.parse_args()
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ws = config.load()
    if not ws.shared.is_dir():
        sys.exit(f"the shared drive is not linked in ({ws.shared} is missing): see WORKSPACE.md section 5")
    targets = {ws.shared / "INDEX.md": index(ws.shared)}
    map_file = ws.root / "WORKSPACE.md"
    targets[map_file] = config.replace_block(map_file.read_text(encoding="utf-8"), "TREE", tree(ws))
    stale = [path for path, text in targets.items() if not path.is_file() or path.read_text(encoding="utf-8") != text]
    if args.check:
        for path in stale:
            print(f"stale: {path.name}: run py -3.12 tools/workspace/index.py")
        if not stale:
            print("the workspace index and the tree are current")
        return 1 if stale else 0
    for path in stale:
        path.write_text(targets[path], encoding="utf-8", newline="\n")
    for path in targets:
        print(f"{'updated' if path in stale else 'unchanged'}: {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
